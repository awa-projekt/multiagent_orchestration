"""Write docs/reference/skills.md: one row per built-in skill.

Run it from the repository root after adding or changing a builtin skill:

    python scripts/gen_skill_matrix.py            # rewrite the page
    python scripts/gen_skill_matrix.py --check    # exit 1 when the page is out of date

tests/docs/test_skills_matrix.py fails while the checked-in page differs from the skills.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

from awa.skills import Skill, SkillRegistry

TARGET = Path(__file__).resolve().parents[1] / "docs" / "reference" / "skills.md"
EXAMPLE_TEST = "tests/unit/test_skills_examples.py::test_skill_example"

# Keyword scan of the skill text. It shows what kind of tool a skill talks about; it is not
# a declaration and not a requirement (no builtin skill sets `allowed-tools`).
TOOL_KINDS: tuple[tuple[str, str], ...] = (
    ("approval tool", r"\bapproval"),
    ("document reading", r"\b(documents?|attachments?|pdf|spreadsheets?|contracts?)\b"),
    ("search or retrieval", r"\b(search|retriev\w*|passages?|knowledge base)\b"),
    ("email or messaging", r"\b(e-?mail|mailbox|inbox|reply|replies)\b"),
    ("records lookup", r"\b(records?|database|price list|catalog|vendor master)\b"),
    ("calendar", r"\bcalendar\b"),
    ("code and tests", r"\b(repository|diff|stack trace|unit tests?|pull request)\b"),
)

_FENCE = re.compile(r"^```[^\n]*\n(.*?)^```", re.DOTALL | re.MULTILINE)


def first_example_block(skill: Skill) -> str:
    """The first fenced block of the skill body: its output format or template.

    Raises:
        ValueError: If the skill body has no fenced block.
    """
    match = _FENCE.search(skill.instructions)
    if match is None:
        raise ValueError(f"skill {skill.name!r} has no fenced output format")
    return match.group(1).rstrip("\n")


def first_example_line(skill: Skill) -> str:
    """The first line of `first_example_block`, as shown on the page."""
    return first_example_block(skill).splitlines()[0].strip()


def purpose(skill: Skill) -> str:
    """The first sentence of the description."""
    text = " ".join(skill.description.split())
    return text.split(". ")[0].rstrip(".") + "."


def tool_kinds(skill: Skill) -> str:
    """Tool kinds the skill text refers to (keyword scan), or the declared `allowed-tools`."""
    if skill.allowed_tools:
        return ", ".join(f"`{name}`" for name in skill.allowed_tools)
    texts = [skill.instructions, *(skill.read_resource(path) for path in skill.resources)]
    text = "\n".join(texts).lower()
    kinds = [label for label, pattern in TOOL_KINDS if re.search(pattern, text)]
    return ", ".join(kinds) or "none"


def table_cell(text: str) -> str:
    """Escape text for one Markdown table cell."""
    return text.replace("|", "\\|").replace("\n", " ")


def render() -> str:
    """Render the whole page from the built-in skills."""
    skills = sorted(SkillRegistry.builtin().all(), key=lambda item: item.name)
    lines = [
        "# Skills",
        "",
        "<!-- Generated by scripts/gen_skill_matrix.py from the built-in skills. Do not edit. -->",
        "",
        f"Every built-in skill and what it is for: {len(skills)} skills, generated from the code.",
        "",
        "```console",
        "awa skills list                     # name and description of every skill",
        "awa skills show approval-requests   # the full text of one skill",
        "```",
        "",
        "An agent gets the full text of its skills in its prompt; with `skill_mode: on_demand` it "
        "sees only their descriptions and loads one with the `load_skill` tool "
        "([Skills](../develop/skills.md#inline-or-on-demand)).",
        "",
        "- **Purpose**: the first sentence of the description.",
        "- **Tool kinds**: what the skill text talks about (a keyword scan, not a requirement).",
        "- **Output starts with**: the first line of the output format in the skill.",
        "- **Example test**: an offline test with a scripted model. It checks that the skill is "
        "found, stays out of the prompt until it is loaded, and returns its output format. It "
        "does not measure answer quality.",
        "",
        "| Skill | Category | Risk | Purpose | Tool kinds | Bundled files | Output starts with "
        "| Example test |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for skill in skills:
        files = ", ".join(f"`{path}`" for path in skill.resources) or "none"
        row = [
            f"`{skill.name}`",
            skill.category or "",
            skill.risk,
            purpose(skill),
            tool_kinds(skill),
            files,
            f"`{first_example_line(skill)}`",
            f"`[{skill.name}]`",
        ]
        lines.append("| " + " | ".join(table_cell(item) for item in row) + " |")
    lines += ["", f"Every example test is `{EXAMPLE_TEST}` with the skill name as parameter.", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current.replace("\r\n", "\n") != text:
            print(f"{TARGET} is out of date; run python scripts/gen_skill_matrix.py")
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
