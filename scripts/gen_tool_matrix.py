"""Write the table of the built-in tools into docs/reference/tools.md.

One row per tool of `awa.toolkits.catalog()`: its risk flags and approval default (from the
catalog), what repeating a call does, whether the page has an executed example for it, and which
contract cases its spec in tests/_helpers/tools_matrix/specs.py has (valid call, invalid call,
hostile calls, injection text, side effect). Only the block between the markers is generated; the
examples below it are written by hand. Run it from the repository root after changing the catalog,
an example or a spec:

    python scripts/gen_tool_matrix.py            # rewrite the table
    python scripts/gen_tool_matrix.py --check    # exit 1 when the table is out of date

tests/docs/test_tools_contract_matrix.py fails while the checked-in page differs from this output.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from _helpers.tools_matrix.specs import ToolSpec

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "docs" / "reference" / "tools.md"
BEGIN = "<!-- generated by scripts/gen_tool_matrix.py: tool table -->"
END = "<!-- end of generated tool table -->"
_TITLE = re.compile(r'^```[\w+-]*[ \t]+title="(?P<title>[^"]+)"', re.MULTILINE)

_EFFECTS = {
    "none": "none",
    "idempotent": "same state when repeated",
    "repeats": "acts again when repeated",
}


def _page() -> str:
    return TARGET.read_text("utf-8").replace("\r\n", "\n")


def example_titles() -> set[str]:
    """The titles of the code blocks on the page."""

    return set(_TITLE.findall(_page()))


def example_file(name: str) -> str:
    """The title of the example script of tool `name` (`awa.x` becomes `tool_awa_x.py`)."""

    return "tool_" + name.replace(".", "_") + ".py"


def _risk(flags: object) -> str:
    names = [
        label
        for flag, label in (
            ("untrusted_input", "untrusted input"),
            ("private_data", "private data"),
            ("external_action", "external action"),
        )
        if getattr(flags, flag)
    ]
    return ", ".join(names) or "none"


def _contract(spec: ToolSpec, gated: bool) -> str:
    parts = ["valid"]
    parts.append("invalid" if spec.invalid is not None else "no arguments")
    hostile = len(spec.hostile)
    parts.append(f"{hostile} hostile" if hostile else "no hostile case needed")
    if spec.poison is not None:
        parts.append("injection framed" if spec.framed else "injection not repeated")
    parts.append("side effect")
    if gated:
        parts.append("approval gate")
    return ", ".join(parts)


def table() -> str:
    """The generated block: the table and what its columns mean."""

    sys.path.insert(0, str(ROOT / "src"))
    sys.path.insert(0, str(ROOT / "tests"))
    from _helpers.tools_matrix.specs import BY_NAME
    from awa.toolkits import catalog

    titles = example_titles()
    rows = []
    for entry in catalog():
        spec = BY_NAME.get(entry.name)
        script = example_file(entry.name)
        has_example = script in titles and script[:-3] + ".out" in titles
        example = f"[`{script}`](#{entry.name})" if has_example else "**missing**"
        contract = _contract(spec, entry.requires_approval) if spec is not None else "**missing**"
        effect = _EFFECTS[spec.effect] if spec is not None else "**missing**"
        approval = "yes" if entry.requires_approval else "no"
        rows.append(
            f"| `{entry.name}` | {entry.category} | {_risk(entry.risk)} "
            f"| {approval} | {effect} | {example} | {contract} |"
        )
    return (
        "| Tool | Category | Risk | Approval default | Side effect | Example | Contract cases |\n"
        "| --- | --- | --- | --- | --- | --- | --- |\n" + "\n".join(rows) + "\n\n"
        "- **Risk** and **Approval default** come from the catalog. A tool created with an "
        "allowlist or in read-only mode can declare a lower risk, and approval can be switched off "
        "per toolkit.\n"
        "- **Side effect** says what repeating the same call does.\n"
        "- **Example** is the runnable file in the section of the tool below.\n"
        "- **Contract cases** are the cases of the tool's spec in "
        "`tests/_helpers/tools_matrix/specs.py`, run by `tests/unit/test_tools_contract_cases.py`: "
        "a valid call, an invalid call refused with a message that names the fix, hostile calls "
        "(path traversal, huge input, private networks, injection into queries, email headers or "
        "templates) and, for tools that read content outsiders can write, planted text that must "
        "come back inside the `<tool_output>` frame.\n"
    )


def render() -> str:
    """The page with its generated block replaced by `table()`."""

    page = _page()
    head, begin, rest = page.partition(BEGIN)
    _, end, tail = rest.partition(END)
    if not begin or not end:
        raise SystemExit(f"{TARGET}: the markers {BEGIN!r} and {END!r} are missing")
    return f"{head}{BEGIN}\n\n{table()}\n{END}{tail}"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if _page() != text:
            print("docs/reference/tools.md is out of date: run python scripts/gen_tool_matrix.py")
            return 1
        return 0
    TARGET.write_text(text, "utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
