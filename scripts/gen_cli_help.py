"""Write the help snapshot and the command reference of `docs/reference/cli.md` from the parser.

    python scripts/gen_cli_help.py            # write the snapshots and the docs block
    python scripts/gen_cli_help.py --check    # exit 1 when a file differs (tests run this)

`awa --help` and the help of every command and subcommand are rendered at a fixed width of 100
columns without colors, in the order of the groups of `awa.cli`, so the snapshot and the
documentation cannot drift from the command line. The `awa init` templates are listed from
`awa.blueprints.scaffold.TEMPLATES`.
"""

from __future__ import annotations

import argparse
import contextlib
import io
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

SNAPSHOTS = ROOT / "tests" / "fixtures" / "cli_help"
CLI_PAGE = ROOT / "docs" / "reference" / "cli.md"
BEGIN = "<!-- generated by scripts/gen_cli_help.py: every command -->"
END = "<!-- end of generated commands -->"
_REPEATED_METAVAR = re.compile(r"(-{1,2}[\w-]+) (\S+), (-{1,2}[\w-]+) \2(?=\s)")


def _plain_terminal() -> None:
    """A fixed width and no colors, whatever the terminal running this script."""

    os.environ["COLUMNS"] = "100"
    os.environ["NO_COLOR"] = "1"
    os.environ["PYTHON_COLORS"] = "0"
    os.environ.pop("FORCE_COLOR", None)


def _output(argv: list[str]) -> str:
    from awa.cli import main

    out = io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.suppress(SystemExit):
        main(argv)
    return out.getvalue()


def texts() -> dict[str, str]:
    """The snapshot file name -> its text."""

    _plain_terminal()
    return {"awa-help.txt": _output(["--help"])}


def _subcommands(parser: argparse.ArgumentParser) -> list[tuple[str, argparse.ArgumentParser]]:
    """The listed subcommands of `parser`, in their order (hidden ones left out)."""

    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            listed = [choice.dest for choice in action._choices_actions]
            return [(name, action.choices[name]) for name in listed]
    return []


def _section(parser: argparse.ArgumentParser, level: int) -> list[str]:
    """A heading and the help of `parser`, then the same for each of its subcommands."""

    lines = [f"{'#' * level} `{parser.prog}`", "", "```text", parser.format_help().rstrip(), "```"]
    for _, child in _subcommands(parser):
        lines += ["", *_section(child, min(level + 1, 4))]
    return lines


def reference(help_text: str) -> str:
    """The generated part of the page: `awa --help`, every command by group, the templates."""

    from awa.blueprints.scaffold import TEMPLATES
    from awa.cli import GROUPS, build_parser

    commands = dict(_subcommands(build_parser()))
    lines = ["## `awa`", "", "```text", help_text.rstrip(), "```"]
    for group, names in GROUPS.items():
        lines += ["", f"## {group}"]
        for name in names:
            lines += ["", *_section(commands[name], 3)]
    lines += ["", "## Templates of `awa init`", "", "| Template | The system |", "| --- | --- |"]
    lines += [f"| `{t.name}` | {t.summary} |" for t in TEMPLATES.values()]
    return "\n".join(lines)


def cli_page(help_text: str) -> str:
    """`docs/reference/cli.md` with its generated block replaced."""

    page = CLI_PAGE.read_text(encoding="utf-8")
    head, begin, rest = page.partition(BEGIN)
    _, end, tail = rest.partition(END)
    if not begin or not end:
        raise SystemExit(f"{CLI_PAGE}: the markers {BEGIN!r} and {END!r} are missing")
    return f"{head}{BEGIN}\n\n{reference(help_text)}\n\n{END}{tail}"


def targets() -> dict[Path, str]:
    """Every generated file -> its expected text."""

    rendered = texts()
    files = {SNAPSHOTS / name: text for name, text in rendered.items()}
    files[CLI_PAGE] = cli_page(rendered["awa-help.txt"])
    return files


def comparable(text: str) -> str:
    """`text` without the help layout that differs between Python versions.

    Before 3.13 argparse repeats the metavar on every option string (`-o OUTPUT, --output OUTPUT`
    instead of `-o, --output OUTPUT`), which also shifts the help column and the usage wrapping;
    this names each metavar once and collapses all whitespace.
    """

    return " ".join(_REPEATED_METAVAR.sub(r"\1, \3 \2", text).split())


def matches(current: str, expected: str) -> bool:
    """Whether a generated file is up to date: exact from Python 3.13, else by `comparable`."""

    if sys.version_info >= (3, 13):
        return current == expected
    return comparable(current) == comparable(expected)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="only compare; exit 1 on a change")
    args = parser.parse_args(argv)
    stale = []
    for path, text in targets().items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current is not None and matches(current, text):
            continue
        stale.append(path)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(text.encode("utf-8"))
    for path in stale:
        verb = "differs" if args.check else "written"
        print(f"{path.relative_to(ROOT).as_posix()}: {verb}")
    if stale and args.check:
        print("run: python scripts/gen_cli_help.py")
    return 1 if stale and args.check else 0


if __name__ == "__main__":
    raise SystemExit(main())
