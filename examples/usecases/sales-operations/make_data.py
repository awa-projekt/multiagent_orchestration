"""Writes the sample data of the sales-operations use case into `data/` (seeded, deterministic).

Test data: generated by make_data.py (fictitious), not company data. Everything is generated here:
a German food wholesaler's order database (`sales.db`, SQLite) with 400 customers, 120 products,
6,000 orders and about 21,000 order lines from 2024-01-02 to 2026-01-09, and the sales targets per
employee (`targets.csv`). Company and person names are built from invented syllables and common
German first names; no real person or company is meant. The names, places and goods are German on
purpose: the use case is a German sales team.

The data is messy the way real exports are: the same country is written several ways
("Deutschland", "DE", "Germany", "BRD"), company names carry stray spaces, cancelled orders stay in
the table (status 'cancelled', they are no revenue), open orders have no shipped date, and a few
products are discontinued but still have stock.

    python make_data.py          # rewrite data/sales.db and data/targets.csv
"""

from __future__ import annotations

import csv
import random
import sqlite3
from contextlib import closing
from datetime import date, timedelta
from pathlib import Path

HERE = Path(__file__).resolve().parent
SEED = 20261008
FIRST_DAY, LAST_DAY = date(2024, 1, 2), date(2026, 1, 9)
CUSTOMERS, PRODUCTS, ORDERS = 400, 120, 6000

SYLLABLES = ["bran", "kor", "dal", "fen", "gar", "hol", "kes", "lor", "mav", "nor", "pel",
             "wen", "ros", "sal", "tav", "vel", "win", "zor", "ard", "bel", "kal", "dun"]  # fmt: skip
TRADES = ["Feinkost", "Lebensmittel", "Getränkehandel", "Gastronomie", "Frischemarkt",
          "Großküchen", "Naturkost", "Partyservice", "Handelshaus", "Bäckerei"]  # fmt: skip
FORMS = ["GmbH", "KG", "OHG", "e.K.", "GmbH & Co. KG", "AG", "GmbH"]
# country: (spellings found in the data, cities)
COUNTRIES = {
    "Deutschland": (
        ["Deutschland", "DE", "Germany", "BRD"],
        ["Hamburg", "München", "Köln", "Nürnberg", "Leipzig", "Würzburg"],
    ),
    "Österreich": (["Österreich", "AT", "Austria"], ["Wien", "Graz", "Linz"]),
    "Schweiz": (["Schweiz", "CH"], ["Zürich", "Basel", "Bern"]),
    "Niederlande": (["Niederlande", "NL"], ["Utrecht", "Venlo"]),
    "Frankreich": (["Frankreich", "FR"], ["Straßburg", "Lyon"]),
    "Polen": (["Polen", "PL"], ["Posen", "Breslau"]),
    "Dänemark": (["Dänemark", "DK"], ["Aarhus", "Odense"]),
}
CATEGORIES = ["Getränke", "Würzmittel", "Süßwaren", "Milchprodukte", "Getreideprodukte",
              "Fleisch und Geflügel", "Obst und Gemüse", "Fisch und Meeresfrüchte"]  # fmt: skip
GOODS = {
    "Getränke": ["Apfelschorle", "Kräutertee", "Malzbier", "Holundersaft", "Espressobohnen"],
    "Würzmittel": ["Senf mittelscharf", "Rapsöl", "Kräuteressig", "Meerrettich", "Currysoße"],
    "Süßwaren": ["Lebkuchen", "Marzipan", "Butterkekse", "Nougatcreme", "Fruchtgummi"],
    "Milchprodukte": ["Bergkäse", "Quark 20 %", "Süßrahmbutter", "Joghurt natur", "Gouda jung"],
    "Getreideprodukte": ["Haferflocken", "Dinkelmehl 630", "Spätzle", "Roggenbrot", "Müsli"],
    "Fleisch und Geflügel": ["Schinkenspeck", "Putenbrust", "Bratwurst", "Leberkäse"],
    "Obst und Gemüse": ["Sauerkraut", "Gewürzgurken", "Rote Bete", "Apfelmus", "Grünkohl"],
    "Fisch und Meeresfrüchte": ["Matjesfilet", "Räucherlachs", "Bismarckhering", "Krabben"],
}
FIRST = ["Anna", "Jonas", "Lena", "Lukas", "Marie", "Felix", "Sophie", "Paul", "Hannah",
         "Leon", "Clara", "Moritz", "Jana", "Tobias", "Katrin", "Jörg"]  # fmt: skip
LAST = ["Brandner", "Kessler", "Dornbach", "Ellwanger", "Fuchsberger", "Gräfe", "Hollerbach",
        "Imhof", "Jäckel", "Kürschner", "Lindemann", "Mösner", "Nägele", "Oberreiter",
        "Pfänder", "Rößler"]  # fmt: skip
SHIPPERS = ["Schnellfracht Nord", "Paketdienst Süd", "Rheintal Logistik"]


def _company(rng: random.Random, used: set[str]) -> str:
    while True:
        root = "".join(rng.choice(SYLLABLES) for _ in range(2)).capitalize()
        name = " ".join(p for p in (root, rng.choice(TRADES), rng.choice(FORMS)) if p)
        if name not in used:
            used.add(name)
            return name


def _messy(rng: random.Random, name: str) -> str:
    """Stray spaces as hand-typed master data has them, in one name of fifteen."""

    return f" {name}" if rng.random() < 0.04 else f"{name}  " if rng.random() < 0.03 else name


def generate(target: Path) -> None:
    rng = random.Random(SEED)
    target.mkdir(parents=True, exist_ok=True)
    database = target / "sales.db"
    database.unlink(missing_ok=True)
    used: set[str] = set()
    with closing(sqlite3.connect(database)) as db:
        db.executescript(
            """
            CREATE TABLE categories (category_id INTEGER PRIMARY KEY, name TEXT NOT NULL);
            CREATE TABLE suppliers (supplier_id INTEGER PRIMARY KEY, company_name TEXT NOT NULL,
              country TEXT);
            CREATE TABLE shippers (shipper_id INTEGER PRIMARY KEY, company_name TEXT NOT NULL);
            CREATE TABLE employees (employee_id INTEGER PRIMARY KEY, first_name TEXT,
              last_name TEXT, title TEXT, region TEXT);
            CREATE TABLE customers (customer_id TEXT PRIMARY KEY, company_name TEXT NOT NULL,
              city TEXT, country TEXT, created_on TEXT);
            CREATE TABLE products (product_id INTEGER PRIMARY KEY, product_name TEXT NOT NULL,
              supplier_id INTEGER REFERENCES suppliers(supplier_id),
              category_id INTEGER REFERENCES categories(category_id), unit_price REAL,
              units_in_stock INTEGER, units_on_order INTEGER, reorder_level INTEGER,
              discontinued INTEGER);
            CREATE TABLE orders (order_id INTEGER PRIMARY KEY,
              customer_id TEXT REFERENCES customers(customer_id),
              employee_id INTEGER REFERENCES employees(employee_id), order_date TEXT,
              required_date TEXT, shipped_date TEXT,
              shipper_id INTEGER REFERENCES shippers(shipper_id), freight REAL, status TEXT);
            CREATE TABLE order_lines (order_id INTEGER REFERENCES orders(order_id),
              product_id INTEGER REFERENCES products(product_id), unit_price REAL,
              quantity INTEGER, discount REAL, PRIMARY KEY (order_id, product_id));
            """
        )
        db.executemany("INSERT INTO categories VALUES (?, ?)", enumerate(CATEGORIES, 1))
        countries = list(COUNTRIES)
        suppliers = [(i, _company(rng, used), rng.choice(countries)) for i in range(1, 21)]
        db.executemany("INSERT INTO suppliers VALUES (?, ?, ?)", suppliers)
        db.executemany("INSERT INTO shippers VALUES (?, ?)", enumerate(SHIPPERS, 1))
        regions = ["Nord", "Süd", "West", "Ost"]
        employees = [
            (i, FIRST[i * 3 % 16], LAST[i * 5 % 16], "Außendienst", regions[i % 4])
            for i in range(1, 10)
        ]
        db.executemany("INSERT INTO employees VALUES (?, ?, ?, ?, ?)", employees)

        customers: list[tuple[str, str, str, str, str]] = []
        weights: list[float] = []
        for _ in range(CUSTOMERS):
            name = _company(rng, used)
            code = "".join(c for c in name.upper() if "A" <= c <= "Z")[:4]
            code += str(sum(1 for c in customers if c[0].startswith(code)))
            country = rng.choices(countries, weights=[55, 14, 10, 7, 5, 5, 4])[0]
            spellings, cities = COUNTRIES[country]
            created = FIRST_DAY - timedelta(days=rng.randint(0, 2000))
            customers.append((code, _messy(rng, name), rng.choice(cities),
                              rng.choice(spellings), created.isoformat()))  # fmt: skip
            weights.append(rng.paretovariate(1.3))  # a few customers buy most
        db.executemany("INSERT INTO customers VALUES (?, ?, ?, ?, ?)", customers)

        products: list[tuple[object, ...]] = []
        for pid in range(1, PRODUCTS + 1):
            category = (pid - 1) % len(CATEGORIES) + 1
            good = rng.choice(GOODS[CATEGORIES[category - 1]])
            brand = "".join(rng.choice(SYLLABLES) for _ in range(2)).capitalize()
            name = f"{brand} {good}"
            level = rng.choice([0, 5, 10, 15, 20, 25, 30])
            stock = rng.randint(0, 120)
            if pid % 9 == 0:  # tight stock on some items
                stock = rng.randint(0, level)
            on_order = rng.choice([0, 0, 0, 10, 20, 40])
            discontinued = 1 if pid % 17 == 0 else 0
            price = round(rng.uniform(2.5, 95.0), 2)
            products.append((pid, name, rng.randint(1, 20), category, price, stock, on_order,
                             level, discontinued))  # fmt: skip
        db.executemany("INSERT INTO products VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)", products)

        span = (LAST_DAY - FIRST_DAY).days
        lines: list[tuple[object, ...]] = []
        orders: list[tuple[object, ...]] = []
        for oid in range(100001, 100001 + ORDERS):
            ordered = FIRST_DAY + timedelta(days=round(span * (oid - 100001) / ORDERS))
            required = ordered + timedelta(days=rng.choice([14, 21, 28]))
            age = (LAST_DAY - ordered).days
            status = "cancelled" if rng.random() < 0.03 else "shipped"
            shipped: str | None = None
            if status == "shipped" and (age > 30 or rng.random() < age / 30):
                late = rng.random() < 0.06
                delay = rng.randint(1, 12) if late else -rng.randint(0, 10)
                shipped = min(required + timedelta(days=delay), LAST_DAY).isoformat()
            elif status == "shipped":
                status = "open"
            customer = rng.choices(customers, weights=weights)[0][0]
            orders.append((oid, customer, rng.randint(1, 9), ordered.isoformat(),
                           required.isoformat(), shipped, rng.randint(1, 3),
                           round(rng.uniform(5, 250), 2), status))  # fmt: skip
            for product in rng.sample(products, rng.randint(1, 6)):
                discount = rng.choice([0, 0, 0, 0, 0.05, 0.1, 0.15, 0.2])
                lines.append((oid, product[0], product[4], rng.randint(1, 60), discount))
        db.executemany("INSERT INTO orders VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)", orders)
        db.executemany("INSERT INTO order_lines VALUES (?, ?, ?, ?, ?)", lines)
        db.commit()
        db.execute("VACUUM")

    # Targets were set a little above or below what each employee then sold.
    sold: dict[tuple[int, int], float] = {}
    by_order = {o[0]: o for o in orders}
    for oid, _, price, quantity, discount in lines:
        order = by_order[oid]
        if order[8] != "cancelled":
            key = (int(order[2]), int(str(order[3])[:4]))
            sold[key] = sold.get(key, 0.0) + float(price) * int(quantity) * (1 - float(discount))
    with (target / "targets.csv").open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(["employee_id", "year", "target_net_revenue"])
        for employee in employees:
            for year in (2024, 2025):
                planned = sold.get((employee[0], year), 0.0) * rng.uniform(0.9, 1.12)
                writer.writerow([employee[0], year, int(round(planned, -4))])


if __name__ == "__main__":
    generate(HERE / "data")
    print(f"wrote {HERE / 'data'}")
