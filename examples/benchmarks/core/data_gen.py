def generate(root: Path = HERE) -> list[Path]:
    """Write every sample file below `root` and return the paths."""

    paths = []
    for name, make in FILES.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(make())
        paths.append(path)
    return paths


def differing(root: Path = HERE) -> list[str]:
    """Names of the files below `root` that are missing or differ from a fresh generation."""

    return [
        name
        for name, make in FILES.items()
        if not (root / name).is_file()
        or _comparable(name, (root / name).read_bytes()) != _comparable(name, make())
    ]


def _comparable(name: str, data: bytes) -> bytes:
    """Text files compare by their lines: a checkout may have changed CRLF and LF."""

    return data.replace(b"\r\n", b"\n") if name.endswith((".csv", ".json")) else data


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="only compare, exit 1 on a difference")
    args = parser.parse_args(argv)
    if args.check:
        changed = differing()
        print("\n".join(changed) if changed else "all sample files are up to date")
        return 1 if changed else 0
    for path in generate():
        print(path.relative_to(HERE))
    return 0


if __name__ == "__main__":
    sys.exit(main())
