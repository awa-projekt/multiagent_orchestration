def _pdf(objects: list[bytes]) -> bytes:
    """A PDF file from numbered object bodies (object 1 is the catalog)."""

    out = bytearray(b"%PDF-1.4\n")
    offsets = []
    for number, body in enumerate(objects, start=1):
        offsets.append(len(out))
        out += b"%d 0 obj\n" % number + body + b"\nendobj\n"
    xref = len(out)
    out += b"xref\n0 %d\n0000000000 65535 f \n" % (len(objects) + 1)
    out += b"".join(b"%010d 00000 n \n" % offset for offset in offsets)
    out += b"trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n" % (
        len(objects) + 1,
        xref,
    )
    return bytes(out)


def _stream(dictionary: bytes, data: bytes) -> bytes:
    return b"<< %s /Length %d >>\nstream\n" % (dictionary, len(data)) + data + b"\nendstream"


def text_pdf(lines: list[str]) -> bytes:
    """A one-page A4 PDF whose text layer holds `lines` (Helvetica, WinAnsi)."""

    def escape(line: str) -> bytes:
        raw = line.encode("cp1252")
        return raw.replace(b"\\", b"\\\\").replace(b"(", b"\\(").replace(b")", b"\\)")

    content = b"BT /F1 11 Tf 56 780 Td 18 TL\n"
    content += b"".join(b"(" + escape(line) + b") Tj T*\n" for line in lines) + b"ET"
    return _pdf(
        [
            b"<< /Type /Catalog /Pages 2 0 R >>",
            b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
            b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R "
            b"/Resources << /Font << /F1 5 0 R >> >> >>",
            _stream(b"", content),
            b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>",
        ]
    )


def scanned_pdf() -> bytes:
    """A one-page PDF that only holds a picture of text lines: no text layer, as a scan."""

    width, height, state = 200, 280, 2024
    rows = bytearray()
    for y in range(height):
        line = y // 14 % 2 == 0 and 20 <= y < 250
        row = bytearray(b"\xf4" * width)
        for x in range(20, 180):
            state = (state * 1103515245 + 12345) % 2**31
            if line and state % 7 < 4:
                row[x] = 40 + state % 60
        rows += row
    image = _stream(
        b"/Type /XObject /Subtype /Image /Width %d /Height %d /ColorSpace /DeviceGray "
        b"/BitsPerComponent 8 /Filter /FlateDecode" % (width, height),
        zlib.compress(bytes(rows), 9),
    )
    return _pdf(
        [
            b"<< /Type /Catalog /Pages 2 0 R >>",
            b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
            b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R "
            b"/Resources << /XObject << /Im0 5 0 R >> >> >>",
            _stream(b"", b"q 595 0 0 842 0 0 cm /Im0 Do Q"),
            image,
        ]
    )


def _normalise_zip(data: bytes, results: dict[str, str] | None = None) -> bytes:
    """The same zip with fixed entry times, and saved results for the formula cells.

    Spreadsheet programs store a formula's result next to it; `openpyxl` writes only
    the formula. `results` maps `"sheetN.xml!A1"` to the number to store.
    """

    out = io.BytesIO()
    with (
        zipfile.ZipFile(io.BytesIO(data)) as source,
        zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as target,
    ):
        for info in sorted(source.infolist(), key=lambda item: item.filename):
            body = source.read(info.filename)
            if results and info.filename.startswith("xl/worksheets/"):
                sheet, text = info.filename.rsplit("/", 1)[1], body.decode()
                for key, value in results.items():
                    name, cell = key.split("!")
                    if name == sheet:
                        pattern = rf'(<c r="{cell}"[^>]*>)(<f>.*?</f>)<v\s*/>|(<c r="{cell}"[^>]*>)(<f>.*?</f>)<v></v>'
                        text, count = re.subn(
                            pattern,
                            lambda m, v=value: f"{m[1] or m[3]}{m[2] or m[4]}<v>{v}</v>",
                            text,
                        )
                        if not count:
                            raise ValueError(f"no formula in {key}")
                body = text.encode()
            if info.filename == "docProps/core.xml":  # openpyxl stamps the time of saving
                stamp = (FIXED_TIME.isoformat() + "Z").encode()
                body = re.sub(rb"(<dcterms:modified[^>]*>)[^<]*", rb"\g<1>" + stamp, body)
            entry = zipfile.ZipInfo(info.filename, date_time=(2024, 10, 1, 8, 0, 0))
            entry.compress_type, entry.external_attr = zipfile.ZIP_DEFLATED, 0o600 << 16
            target.writestr(entry, body)
    return out.getvalue()


def timesheet_xlsx() -> bytes:
    """A contractor's invoice as a workbook: dates, hours and formulas (the VAT line uses
    the old 16 % rate, which the validation rules must catch)."""

    import openpyxl

    book = openpyxl.Workbook()
    head = book.active
    assert head is not None
    head.title = "Kopf"
    for row in [
        ("Rechnungsnummer", "LN-2024-17"),
        ("Lieferant", "Freelance Dev Meyer"),
        ("USt-IdNr", "DE844444444"),
        ("Rechnungsdatum", date(2024, 10, 1)),
        ("Fällig am", date(2024, 10, 31)),
        ("Bestellung", "PO-4502"),
        ("IBAN", "DE75512108001245126199"),
        ("Währung", "EUR"),
    ]:
        head.append(row)
    work = book.create_sheet("Leistungen")
    work.append(("Datum", "Tätigkeit", "Stunden", "Satz_EUR", "Betrag_EUR"))
    hours = [8, 8, 8, 8, 8, 8, 6, 6]
    days = [date(2024, 9, d) for d in (2, 3, 4, 5, 6, 9, 10, 11)]
    results = {}
    for index, (day, h) in enumerate(zip(days, hours, strict=True), start=2):
        work.append((day, "Softwareentwicklung", h, 80, f"=C{index}*D{index}"))
        results[f"sheet2.xml!E{index}"] = str(h * 80)
    work.append(("Netto", None, None, None, "=SUM(E2:E9)"))
    work.append(("USt 16 %", None, None, None, "=ROUND(E10*0.16,2)"))
    work.append(("Brutto", None, None, None, "=E10+E11"))
    results |= {"sheet2.xml!E10": "4800", "sheet2.xml!E11": "768", "sheet2.xml!E12": "5568"}
    for column, width in zip("ABCDE", (14, 22, 10, 10, 12), strict=True):
        work.column_dimensions[column].width = width
    book.properties.creator = book.properties.lastModifiedBy = "awa benchmark"
    book.properties.created = book.properties.modified = FIXED_TIME
    buffer = io.BytesIO()
    book.save(buffer)
    return _normalise_zip(buffer.getvalue(), results)


